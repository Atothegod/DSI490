"""Model wording grounded in a Python reply plan (Design Decisions 6.8).

Validation checks the plan's fields, citations, numbers, explicit area names and
forbidden claims. It cannot prove Thai semantic equivalence. Factual summaries,
report delivery and hotline blocks are never generated by this model.
"""
import json
import re

import dspy
from pydantic import Field
from .schemas import StrictModel
from .safety import redact_identifiers, redact_phones


class Wording(StrictModel):
    acknowledgement: str = ""
    questions: dict[str, str] = Field(default_factory=dict)
    knowledge_answer: str = ""
    source_ids: list[str] = Field(default_factory=list)


class ComposeReply(dspy.Signature):
    """เรียบเรียงภาษาไทยให้เข้ากับบทสนทนาจากแผนที่โค้ดกำหนดเท่านั้น ไม่ตัดสินใจแทนโค้ด
    - message/recent_messages: บริบทบทสนทนา confirmed_state: ข้อมูลที่มีจริง changes: สิ่งที่เปลี่ยนรอบนี้
    - acknowledgement: เกริ่นหรือรับทราบสั้น ๆ ไม่ถามคำถาม ไม่สรุปข้อเท็จจริง ไม่แจ้งสถานะการส่ง
    - questions: ต้องมี key ครบตาม question_hints เท่านั้น แต่เรียบเรียงถ้อยคำใหม่ได้ ไม่ต้องคัด template
      ถามเรื่องตาม key นั้นให้ชัด ไม่ถาม field อื่นหรือเรื่องที่ทราบแล้ว ไม่เกิน 2 field ต่อรอบ
      question_hints เป็นตัวอย่างความหมาย ไม่ใช่ชุดคำตอบให้เลือก หากเป็นคำขอพิกัดต้องรักษาคำอธิบาย
      วัตถุประสงค์และสิทธิข้ามตาม hint ให้ครบ ส่วนข้อความ consent โค้ดจะล็อกไว้ต่างหาก
    - knowledge_answer: เรียบเรียงหรือสรุปใหม่จาก reviewed_text ใน evidence เท่านั้น ไม่ต้องคัดคำต่อคำ
      ห้ามใช้ความรู้ภายนอก ห้ามกลับความหมายคำห้าม/คำเตือน ระบุ source_ids ของทุกแถวที่ใช้จริง
      ไม่มีหลักฐานตอบได้ให้เว้นว่างทั้ง knowledge_answer และ source_ids
    ห้ามแต่งข้อมูล ตัวเลข หรือชื่อพื้นที่ ห้ามสร้างเบอร์โทร URL สายด่วน สถานะการส่ง สรุปรายงาน
    หรืออ้างว่าเจ้าหน้าที่รับเรื่อง/กำลังไป/ช่วยแล้ว โค้ดจะสร้างส่วนที่ล็อกไว้เอง
    แต่ละส่วนลงท้ายค่ะ ความยาวรวมไม่เกิน max_chars ตรวจไม่ผ่านจะใช้ template โดยไม่เรียกซ้ำ"""
    plan: str = dspy.InputField()
    result: Wording = dspy.OutputField()


class ResponseComposer(dspy.Module):
    def __init__(self, max_chars=1200):
        super().__init__()
        self.predict = dspy.Predict(ComposeReply)
        self.max_chars = max_chars

    def forward(self, plan):
        try:
            with dspy.context(adapter=dspy.ChatAdapter(use_json_adapter_fallback=False)):
                result = self.predict(plan=json.dumps({**plan, "max_chars":self.max_chars}, ensure_ascii=False)).result
            return result if validate_wording(result, plan, self.max_chars) else None
        except Exception:
            return None


FIELD_MARKERS = {
    "location_area": ("ที่ไหน", "บริเวณไหน", "จุดไหน", "หมู่บ้าน", "ตำบล", "อำเภอ", "จุดเกิดเหตุ", "พื้นที่ใด", "พื้นที่ไหน"),
    "location_coordinates": ("พิกัด", "ตำแหน่ง", "หมุด", "แผนที่", "gps"),
    "location_landmark": ("จุดสังเกต", "สถานที่ใกล้", "วัด", "โรงเรียน", "ถนน", "ใกล้เคียง"),
    "situation": ("เกิดอะไร", "สถานการณ์", "เกิดเหตุ", "เป็นอย่างไร", "เป็นยังไง", "พบอะไร", "เกิดขึ้น", "น้ำท่วม"),
    "needs": ("ต้องการ", "ให้ช่วย", "อยากให้", "ช่วยเรื่อง", "ขาดอะไร"),
    "affected_people": ("ได้รับผลกระทบ", "เดือดร้อน", "กี่คน", "จำนวนคน", "คนอยู่", "มีคน", "จำนวนผู้"),
    "vulnerable_people": ("ผู้สูงอายุ", "เด็ก", "ผู้พิการ", "กลุ่มเปราะบาง", "ผู้ป่วย", "หญิงตั้งครรภ์", "ดูแลเป็นพิเศษ"),
    "water_level": ("ระดับน้ำ", "น้ำสูง", "น้ำลึก", "ถึงส่วนไหน", "สูงแค่ไหน", "น้ำถึง"),
    "contact": ("เบอร์", "ติดต่อ", "โทร"),
}
# Additional requests inside an otherwise correctly keyed question must not escape the plan.
EXTRA_REQUESTS = {
    "location_area": r"(?:ตำบล|อำเภอ|หมู่บ้าน)(?:ใด|ไหน|อะไร)|(?:เกิดเหตุ|แจ้งเหตุ)(?:อยู่)?ที่ไหน",
    "location_coordinates": r"(?:ขอ|แชร์|ส่ง|บอก).{0,16}(?:พิกัด|ตำแหน่ง|หมุด)",
    "location_landmark": r"(?:ขอ|บอก|มี).{0,12}จุดสังเกต",
    "situation": r"เกิดอะไรขึ้น|สถานการณ์(?:เป็นอย่างไร|เป็นยังไง)",
    "needs": r"ต้องการ(?:ความช่วยเหลือ)?(?:อะไร|เรื่องใด|เรื่องไหน)|(?:ให้|อยากให้)ช่วย(?:อะไร|เรื่องใด)",
    "affected_people": r"กี่คน|(?:ขอ|ทราบ|บอก).{0,12}(?:จำนวนคน|จำนวนผู้ได้รับผลกระทบ)",
    "vulnerable_people": r"มี(?:เด็ก|ผู้สูงอายุ|ผู้พิการ|กลุ่มเปราะบาง|ผู้ป่วย|หญิงตั้งครรภ์).{0,50}(?:ไหม|หรือไม่|หรือเปล่า)",
    "water_level": r"(?:ขอ|ทราบ|บอก).{0,12}ระดับน้ำ|น้ำ(?:สูง|ลึก).{0,12}(?:แค่ไหน|เท่าไร|เท่าไหร่)",
    "contact": r"(?:ขอ|ฝาก|บอก|แจ้ง).{0,12}(?:เบอร์โทร|เบอร์ติดต่อ)",
}
FORBIDDEN = (
    r"เจ้าหน้าที่.{0,15}(?:กำลังไป|จะไป|รับเรื่องแล้ว|กำลังเดินทาง|กำลังมา|มาถึงแล้ว)",
    r"(?:กำลัง|จะ)(?:จัด)?ส่ง(?:ทีม|เจ้าหน้าที่|ความช่วยเหลือ|กู้ภัย)",
    r"(?:ได้รับ|ส่ง|จัดส่ง|ส่งทีม|ส่งเจ้าหน้าที่).{0,12}(?:ความช่วยเหลือ|ช่วยเหลือ|กู้ภัย).{0,8}แล้ว",
    r"(?:บันทึก|ส่งต่อ|ส่งรายงาน|ส่งข้อมูล).{0,20}แล้ว",
    r"(?:ได้รับความช่วยเหลือแล้ว|ทีมกู้ภัยกำลังเดินทาง|Agent\s*2)",
)
THAI_DIGITS = str.maketrans("๐๑๒๓๔๕๖๗๘๙", "0123456789")


def _numbers(text):
    return set(re.findall(r"\d+(?:\.\d+)?", str(text).translate(THAI_DIGITS)))


def _facts(plan):
    state = plan.get("confirmed_state", {})
    # Do not let random IDs, timestamps, ask counts or version numbers authorize invented facts.
    return {name:field["value"] for name,field in state.items()
            if isinstance(field,dict) and field.get("status") == "known" and "value" in field}


def _valid_places(text, facts):
    for match in re.finditer(r"(?:ตำบล|อำเภอ|จังหวัด|หมู่บ้าน|ต\.|อ\.|จ\.)\s*([ก-๙A-Za-z]+)", text):
        name = re.split(r"(?:ค่ะ|ครับ|นะคะ|ในอำเภอ|ในจังหวัด|และ|หรือ)", match.group(1))[0]
        if not name or name.startswith(("ใด", "ไหน", "อะไร", "ที่", "หรือ")):
            continue
        if name not in facts:
            return False
    return True


def validate_wording(result, plan, max_chars=1200):
    hints = plan.get("question_hints", {})
    if len(hints) > 2 or set(result.questions) != set(hints):
        return False
    state = plan.get("confirmed_state", {})
    for key, question in result.questions.items():
        if not question.strip() or key not in FIELD_MARKERS or not any(m in question.lower() for m in FIELD_MARKERS[key]):
            return False
        field = state.get("contact_ask" if key == "contact" else key, {})
        area_pending = key == "location_area" and (field.get("value") or {}).get("match_status") in {"ambiguous", "not_found", "pending_tambon"}
        if field.get("status") in {"known", "unknown", "declined", "unanswered"} and not area_pending:
            return False
        if question.count("?") > 1:
            return False
    all_questions = " ".join(result.questions.values())
    for key, pattern in EXTRA_REQUESTS.items():
        if key in hints or not re.search(pattern, all_questions):
            continue
        if key == "affected_people" and "vulnerable_people" in hints and not re.search(r"ผู้ได้รับผลกระทบ|คนทั้งหมด", all_questions):
            continue  # counts of the requested vulnerable groups belong to that field
        return False
    # Formal notice and consent wording must not be rewritten by the LLM.
    if "location_coordinates" in hints:
        question = result.questions["location_coordinates"]
        if not all(part in question for part in ("จุดเกิดเหตุ", "รายงาน", "ผู้ดูแลรายงาน", "ข้าม")):
            return False
    if result.acknowledgement:
        if re.search(r"\?|ไหม|หรือไม่|หรือเปล่า|ขอทราบ", result.acknowledgement) or _numbers(result.acknowledgement):
            return False
    evidence = {e["chunk_id"]:e for e in plan.get("evidence", [])}
    if result.knowledge_answer:
        if not result.source_ids or len(result.source_ids) != len(set(result.source_ids)) or not set(result.source_ids) <= set(evidence):
            return False
    elif result.source_ids:
        return False
    parts = [result.acknowledgement, *result.questions.values(), result.knowledge_answer]
    text = "\n".join(parts)
    if len(text) > max_chars or any(part and not part.rstrip().endswith("ค่ะ") for part in parts):
        return False
    if redact_phones(text).has_phone or redact_identifiers(text) != text:
        return False
    if re.search(r"(?:โทร|เบอร์|สายด่วน)\s*\d{3,}|https?://", text):
        return False
    if any(re.search(pattern, text, re.IGNORECASE) for pattern in FORBIDDEN):
        return False
    confirmed = json.dumps(_facts(plan), ensure_ascii=False)
    cited = " ".join(evidence[source]["reviewed_text"] for source in result.source_ids)
    # Questions can use confirmed facts; knowledge must use only the evidence actually cited.
    if not _numbers(all_questions) <= _numbers(confirmed) or not _valid_places(all_questions, confirmed):
        return False
    if not _numbers(result.knowledge_answer) <= _numbers(cited) or not _valid_places(result.knowledge_answer, cited):
        return False
    if not _valid_places(result.acknowledgement, confirmed):
        return False
    return True
